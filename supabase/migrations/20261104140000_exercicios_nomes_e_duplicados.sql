-- 3. Mescla dos cardios duplicados.
update public.exercises m
   set name_en = coalesce(m.name_en, v.en),
       instructions = coalesce(m.instructions, g.instructions),
       execution = case when coalesce(cardinality(m.execution), 0) = 0 then g.execution else m.execution end,
       execution_es = case when coalesce(cardinality(m.execution_es), 0) = 0 then g.execution_es else m.execution_es end
  from (values
    ('Bicicleta Ergométrica', 'Bicycling_Stationary', 'Stationary Bike'),
    ('Elíptico', 'Elliptical_Trainer', 'Elliptical Trainer'),
    ('Pular Corda', 'Rope_Jumping', 'Jump Rope'),
    ('Remo Ergômetro', 'Rowing_Stationary', 'Rowing Machine'),
    ('Corrida na Esteira', 'Running_Treadmill', 'Treadmill Running'),
    ('Escada', 'Stairmaster', 'Stair Climber'),
    ('Caminhada', 'Walking_Treadmill', 'Walking')
  ) as v(manual, gemeo, en)
  join public.exercises g on g.external_id = v.gemeo and g.owner_id is null
 where m.owner_id is null and m.external_id is null and m.name = v.manual and m.deleted_at is null;

delete from public.exercises g
 using (values
    ('Bicicleta Ergométrica', 'Bicycling_Stationary'),
    ('Elíptico', 'Elliptical_Trainer'),
    ('Pular Corda', 'Rope_Jumping'),
    ('Remo Ergômetro', 'Rowing_Stationary'),
    ('Corrida na Esteira', 'Running_Treadmill'),
    ('Escada', 'Stairmaster'),
    ('Caminhada', 'Walking_Treadmill')
  ) as v(manual, gemeo)
 where g.owner_id is null
   and g.external_id = v.gemeo
   and exists (select 1 from public.exercises m
                where m.owner_id is null and m.external_id is null
                  and m.deleted_at is null and m.name = v.manual)
   and not exists (select 1 from public.workout_sets s where s.exercise_id = g.id)
   and not exists (select 1 from public.workout_template_exercises t where t.exercise_id = g.id);
